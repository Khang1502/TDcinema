document.addEventListener('DOMContentLoaded', () => {
    const form = document.querySelector('[data-level-editor]');
    if (!form) return;
    const thresholds = JSON.parse(form.querySelector('[data-level-thresholds]').textContent);
    const points = form.elements.min_points;
    const benefits = form.elements.benefits_text;
    const card = form.querySelector('[data-level-card]');
    const colors = [...form.querySelectorAll('input[name=color]')].map(input => input.value);
    const formatter = new Intl.NumberFormat('vi-VN');
    const update = () => {
        const name = form.elements.name.value.trim();
        const amount = points.value === '' ? null : points.valueAsNumber;
        const active = form.elements.is_active.value === '1';
        const duplicate = thresholds.find(level => String(level.id) !== form.dataset.levelId && amount !== null && Number(level.min_points) === amount);
        const pointsMessage = duplicate ? `Mốc Stars này đang dùng cho hạng ${duplicate.name}. Hãy chọn mốc khác.` : '';
        points.setCustomValidity(pointsMessage);
        const pointsError = form.querySelector('[data-level-points-error]');
        pointsError.textContent = pointsMessage;
        pointsError.hidden = !pointsMessage;
        const lines = benefits.value.split(/\r\n|[\n\r\u0085\u2028\u2029]/).map(line => line.trim()).filter(Boolean);
        const benefitsMessage = lines.length > 12 ? 'Tối đa 12 quyền lợi. Vui lòng bỏ bớt dòng.' : lines.some(line => Array.from(line).length > 160) ? 'Mỗi quyền lợi không quá 160 ký tự. Vui lòng rút gọn nội dung.' : '';
        benefits.setCustomValidity(benefitsMessage);
        const benefitError = form.querySelector('[data-level-benefit-error]');
        benefitError.textContent = benefitsMessage;
        benefitError.hidden = !benefitsMessage;
        const counter = form.querySelector('[data-level-benefit-count]');
        counter.textContent = `${lines.length}/12 quyền lợi`;
        counter.classList.toggle('is-invalid',!!benefitsMessage);
        card.classList.remove(...colors);
        const selectedColor = form.elements.color.value;
        card.classList.add(selectedColor);
        const selectedColorInput = form.querySelector(`input[name=color][value="${selectedColor}"]`);
        const colorOwners = thresholds.filter(level => level.color === selectedColor);
        const ownerNames = colorOwners.map(level => `${level.name}${String(level.id) === form.dataset.levelId ? ' (hạng này)' : ''}${!level.is_active ? ' (đang tắt)' : ''}`);
        const colorNote = `${selectedColorInput.dataset.colorLabel} · ${ownerNames.length ? 'Đã dùng: '+ownerNames.join(', ') : 'Chưa sử dụng'}`;
        const colorUsage = form.querySelector('[data-level-color-usage]');
        if (colorUsage.textContent !== colorNote) colorUsage.textContent = colorNote;
        colorUsage.classList.toggle('is-used',!!ownerNames.length);
        form.querySelector('[data-level-preview-name]').textContent = name || 'Tên cấp bậc';
        form.querySelector('[data-level-preview-description]').textContent = form.elements.description.value.trim() || 'Đặc quyền dành cho thành viên';
        form.querySelector('[data-level-preview-points]').textContent = Number.isFinite(amount) ? `Từ ${formatter.format(amount)} Stars` : 'Chưa đặt mốc Stars';
        const discount = Number(form.elements.discount_percent.value);
        const previewDiscount = form.querySelector('[data-level-preview-discount]');
        previewDiscount.firstChild.textContent = `${Number.isFinite(discount) ? Math.min(100,Math.max(0,discount)) : 0}% `;
        const status = form.querySelector('[data-level-preview-status]');
        status.textContent = active ? 'Đang bật' : 'Đang tắt';
        status.classList.toggle('is-disabled',!active);
        form.querySelector('[data-level-preview-rule]').textContent = !active ? 'Hạng đang tắt, không dùng để xét hạng hoặc giảm giá.' : Number.isFinite(amount) ? `Thành viên đạt tối thiểu ${formatter.format(amount)} Stars sẽ được xét vào hạng này.` : 'Nhập mốc Stars để đặt điều kiện xét hạng.';
        const list = form.querySelector('[data-level-preview-benefits]');
        list.replaceChildren();
        if (!lines.length) {
            const empty = document.createElement('li');
            empty.className = 'is-empty';
            empty.textContent = 'Thêm quyền lợi để xem nội dung tại đây.';
            list.append(empty);
        } else lines.slice(0,12).forEach(line => {
            const row = form.querySelector('[data-level-benefit-template]').content.firstElementChild.cloneNode(true);
            row.querySelector('span').textContent = line;
            list.append(row);
        });
    };
    form.addEventListener('input',update);
    form.addEventListener('change',update);
    form.addEventListener('reset',() => queueMicrotask(update));
    update();
});
